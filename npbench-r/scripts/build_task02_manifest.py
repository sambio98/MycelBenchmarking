"""Build tasks/02_salinispora_bgc/data.manifest.json from NCBI RefSeq.

One-off operational script. The genome set is defined by the fixed query below,
not by a hand-curated list, so it can be re-derived. The resulting manifest is
the frozen record: once committed, the task is graded against exactly these
files and checksums, whatever NCBI does later.

Run from the npbench-r directory:
    python scripts/build_task02_manifest.py
"""

from __future__ import annotations

import json
import sys
import urllib.parse
import urllib.request
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from npbench.build.manifest import Entry, describe, dump_manifest, sha256_file  # noqa: E402

TASK = Path(__file__).resolve().parents[1] / "tasks" / "02_salinispora_bgc"

# Fixed selection rule. Letzel et al. 2017 analysed 119 Salinispora draft
# genomes from JGI IMG; those IMG IDs no longer resolve one-to-one, so the task
# is staged from RefSeq instead and the genome set is declared here rather than
# taken from the paper. Assembly level is restricted so every genome is at
# least scaffold-quality: contig-level assemblies fragment BGCs differently and
# would make the cluster inventory depend on assembly quality rather than on
# the agent's analysis.
TAXON = "Salinispora"
LEVELS = ("complete_genome", "scaffold")
DATASETS_API = "https://api.ncbi.nlm.nih.gov/datasets/v2alpha"


def _get(url: str) -> dict:
    request = urllib.request.Request(url, headers={"User-Agent": "npbench-r/0.1"})
    with urllib.request.urlopen(request, timeout=180) as response:
        return json.loads(response.read())


def select_assemblies() -> list[dict]:
    query = urllib.parse.urlencode(
        {
            "page_size": 1000,
            "filters.assembly_source": "refseq",
            "filters.assembly_level": LEVELS,
            "filters.assembly_version": "current",
        },
        doseq=True,
    )
    report = _get(f"{DATASETS_API}/genome/taxon/{TAXON}/dataset_report?{query}")
    chosen = []
    for item in report.get("reports", []):
        info = item["assembly_info"]
        chosen.append(
            {
                "accession": item["accession"],
                "organism": item["organism"]["organism_name"],
                "strain": item["organism"].get("infraspecific_names", {}).get("strain", ""),
                "level": info["assembly_level"],
                "name": info["assembly_name"],
            }
        )
    # Sort by accession so the manifest order is stable across runs.
    return sorted(chosen, key=lambda a: a["accession"])


def ftp_url(accession: str, assembly_name: str) -> str:
    """RefSeq layout: .../GCF/000/016/425/GCF_000016425.1_ASM1642v1/<...>_genomic.fna.gz"""
    digits = accession.split("_")[1].split(".")[0]
    triplets = "/".join(digits[i:i + 3] for i in range(0, 9, 3))
    safe_name = assembly_name.replace(" ", "_")
    stem = f"{accession}_{safe_name}"
    return (
        f"https://ftp.ncbi.nlm.nih.gov/genomes/all/GCF/{triplets}/{stem}/"
        f"{stem}_genomic.fna.gz"
    )


def main() -> int:
    assemblies = select_assemblies()
    print(f"selected {len(assemblies)} assemblies", flush=True)

    entries: list[Entry] = []
    strains = []
    for index, assembly in enumerate(assemblies, start=1):
        accession = assembly["accession"]
        target = f"data/genomes/{accession}.fna.gz"
        staged = TASK / target
        url = ftp_url(accession, assembly["name"])
        try:
            if staged.is_file():
                entry = Entry(path=target, bytes=staged.stat().st_size,
                              sha256=sha256_file(staged), url=url, accession=accession)
            else:
                entry = describe(url, target, accession=accession)
        except Exception as exc:
            print(f"  !! {accession}: {exc}", flush=True)
            return 1
        entries.append(entry)
        strains.append({**assembly, "file": target})
        if index % 10 == 0 or index == len(assemblies):
            print(f"  {index}/{len(assemblies)}", flush=True)

    dump_manifest(entries, TASK / "data.manifest.json")
    total = sum(e.bytes for e in entries)
    print(f"wrote manifest: {len(entries)} files, {total / 1e6:.1f} MB")

    # The strain table is an input the agent gets, not an answer. It is a few KB
    # of metadata generated by this script rather than a raw payload, so it is
    # committed at the task root instead of being staged under data/ -- that
    # keeps `make fetch` sufficient to assemble a runnable task.
    (TASK / "strains.tsv").write_text(
        "accession\torganism\tstrain\tassembly_level\tfile\n"
        + "".join(
            f"{s['accession']}\t{s['organism']}\t{s['strain']}\t{s['level']}\t{s['file']}\n"
            for s in strains
        )
    )
    print(f"wrote {TASK / 'strains.tsv'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
