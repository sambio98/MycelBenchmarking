"""Bundle contract validation.

Checks a task directory against PROJECT.md §6 and the hard rules in CLAUDE.md,
before any data is fetched and again after truth/ is generated. Everything it
can check without the payload it checks always; the checks that need truth/ or
data/ run when those directories are present and are reported as skipped when
they are not, because `make validate` runs before `make fetch`.

The validator is not the real gate. That is `make selfgrade`, where the
reference solution must score 1.00. This catches the contract breaks that would
otherwise surface as a confusing 0.00 three hours into a run.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from pathlib import Path

import pandas as pd
import yaml

from ..grading.config import ALIGNED_METRICS, ConfigError, GradingConfig, load_grading_config
from ..grading.normalise import normalise_all

REQUIRED_FILES = ("task.yaml", "prompt.md", "grading.yaml", "data.manifest.json")
REQUIRED_DIRS = ("solution", "environment")

# PROJECT.md §6: the prompt has four parts, following BixBench3.
PROMPT_SECTIONS = {
    "general instructions": ("instruction",),
    "research objective": ("objective", "research goal"),
    "method guidance": ("method",),
    "required outputs": ("required output", "outputs"),
}

SHA256 = re.compile(r"[0-9a-f]{64}")

# Spelled out for the cases a task author hits most. Anything else carries its
# own detail (a column name, a parser error) and is passed through verbatim.
UNREADABLE_TRUTH = {
    "file_missing": "declared in grading.yaml but not present in truth/",
    "file_empty": "is empty",
    "no_data_rows": "has a header but no data rows",
}
UNPINNED = {"latest", "*", "", "any"}


@dataclass(frozen=True)
class Finding:
    level: str  # "error" or "note"
    where: str
    message: str

    def __str__(self) -> str:
        return f"{self.level.upper():5} {self.where}: {self.message}"


def _error(where: str, message: str) -> Finding:
    return Finding("error", where, message)


def _note(where: str, message: str) -> Finding:
    return Finding("note", where, message)


# --------------------------------------------------------------------------- layout


def _check_layout(task_dir: Path) -> list[Finding]:
    findings = []
    for name in REQUIRED_FILES:
        if not (task_dir / name).is_file():
            findings.append(_error(name, "required file is missing"))
    for name in REQUIRED_DIRS:
        if not (task_dir / name).is_dir():
            findings.append(_error(f"{name}/", "required directory is missing"))
    return findings


def _check_solution(task_dir: Path) -> list[Finding]:
    """CLAUDE.md: truth is generated by a committed script."""
    solution = task_dir / "solution"
    if not solution.is_dir():
        return []
    scripts = [p for p in solution.rglob("*") if p.suffix in {".py", ".sh", ".R", ".nf"}]
    if not scripts:
        return [
            _error(
                "solution/",
                "holds no script; every file in truth/ must be regenerable from a "
                "committed script, or it is not usable as ground truth",
            )
        ]
    return []


def _check_environment(task_dir: Path) -> list[Finding]:
    """CLAUDE.md: environments are pinned or they are wrong."""
    environment = task_dir / "environment"
    if not environment.is_dir():
        return []
    pinned = [
        p
        for p in environment.rglob("*")
        if p.name == "Dockerfile" or p.suffix == ".lock" or p.name.endswith("-lock.yml")
    ]
    if not pinned:
        return [
            _error(
                "environment/",
                "holds no Dockerfile and no conda lock file; a bundle without a "
                "pinned environment cannot reproduce its own truth",
            )
        ]
    return []


# ----------------------------------------------------------------------- task.yaml


def _check_task_yaml(task_dir: Path) -> list[Finding]:
    path = task_dir / "task.yaml"
    if not path.is_file():
        return []
    try:
        meta = yaml.safe_load(path.read_text())
    except yaml.YAMLError as exc:
        return [_error("task.yaml", f"not valid YAML: {exc}")]
    if not isinstance(meta, dict):
        return [_error("task.yaml", "top level must be a mapping")]

    findings = []
    for field in ("task_id", "title", "source", "categories", "depth", "tool_versions", "runtime"):
        if field not in meta:
            findings.append(_error("task.yaml", f"missing required field {field!r}"))

    if meta.get("task_id") not in (None, task_dir.name):
        findings.append(
            _error("task.yaml", f"task_id {meta['task_id']!r} does not match directory "
                                f"name {task_dir.name!r}")
        )
    if isinstance(meta.get("source"), dict):
        for field in ("citation", "doi"):
            if not meta["source"].get(field):
                findings.append(_error("task.yaml", f"source is missing {field!r}"))
    elif "source" in meta:
        findings.append(_error("task.yaml", "source must be a mapping with citation and doi"))

    if not isinstance(meta.get("depth"), int) or isinstance(meta.get("depth"), bool):
        if "depth" in meta:
            findings.append(_error("task.yaml", "depth must be an integer (PROJECT.md §8)"))
    if "categories" in meta and not (
        isinstance(meta["categories"], list) and meta["categories"]
    ):
        findings.append(_error("task.yaml", "categories must be a non-empty list"))

    if not str(meta.get("truth_provenance", "")).strip():
        findings.append(
            _error(
                "task.yaml",
                "missing 'truth_provenance'. Every bundle must say in prose where its "
                "truth came from, because 'generated by our pinned tool run' and "
                "'taken from the paper' are graded the same way but mean different "
                "things to a reader of the results",
            )
        )
    findings.extend(_check_tool_versions(meta.get("tool_versions")))
    findings.extend(_check_runtime(meta.get("runtime")))
    findings.extend(_check_network(meta))

    steps = ((meta.get("solution") or {}) if isinstance(meta.get("solution"), dict) else {})
    declared = steps.get("steps")
    if not (isinstance(declared, list) and declared and all(isinstance(s, str) for s in declared)):
        findings.append(
            _error(
                "task.yaml",
                "missing 'solution.steps': the commands that regenerate truth/. Without "
                "them truth cannot be reproduced from a committed script",
            )
        )
    return findings


def _check_network(meta: dict) -> list[Finding]:
    """CLAUDE.md: do not leak answers.

    Checks only that the task has declared a policy and that the policy covers
    the obvious path to its own source study. Whether the truth is reachable by
    some other allowed route is a judgement a person has to make per task; this
    catches the case of nobody having thought about it at all.
    """
    network = meta.get("network")
    if not isinstance(network, dict):
        return [
            _error(
                "task.yaml",
                "missing a 'network' block declaring deny_terms for the adjudicator",
            )
        ]
    terms = network.get("deny_terms")
    if not (isinstance(terms, list) and any(str(t).strip() for t in terms)):
        return [_error("task.yaml", "network.deny_terms must be a non-empty list")]

    findings = []
    folded = [str(t).strip().casefold() for t in terms]
    doi = str((meta.get("source") or {}).get("doi") or "").strip().casefold()
    if doi and not any(doi in term or term in doi for term in folded):
        findings.append(
            _error(
                "task.yaml",
                f"network.deny_terms does not cover the source DOI {doi!r}, so the "
                f"paper is one search away",
            )
        )
    return findings


def _check_tool_versions(versions: object) -> list[Finding]:
    if versions is None:
        return []
    if not isinstance(versions, dict) or not versions:
        return [_error("task.yaml", "tool_versions must be a non-empty mapping")]
    findings = []
    for tool, version in versions.items():
        text = str(version).strip()
        if text.casefold() in UNPINNED or not any(c.isdigit() for c in text):
            findings.append(
                _error(
                    "task.yaml",
                    f"tool_versions[{tool!r}] is {version!r}, not an exact version. "
                    f"antiSMASH detects different cluster type counts across major "
                    f"versions, so a truth artifact is only valid against the exact "
                    f"version that produced it",
                )
            )
    return findings


def _check_runtime(runtime: object) -> list[Finding]:
    if runtime is None:
        return []
    if not isinstance(runtime, dict):
        return [_error("task.yaml", "runtime must be a mapping")]
    findings = []
    for field in ("vcpus", "ram_gb", "wall_clock_hours"):
        if field not in runtime:
            findings.append(_error("task.yaml", f"runtime is missing {field!r}"))
    hours = runtime.get("wall_clock_hours")
    if isinstance(hours, (int, float)) and not isinstance(hours, bool) and hours > 24:
        findings.append(
            _error("task.yaml", f"runtime.wall_clock_hours is {hours}, over the 24 hour cap")
        )
    return findings


# ----------------------------------------------------------------------- prompt.md


def _check_prompt(task_dir: Path, config: GradingConfig | None) -> list[Finding]:
    path = task_dir / "prompt.md"
    if not path.is_file():
        return []
    text = path.read_text()
    folded = text.casefold()
    findings = []
    for section, keywords in PROMPT_SECTIONS.items():
        if not any(k in folded for k in keywords):
            findings.append(
                _error("prompt.md", f"has no {section} section (PROJECT.md §6)")
            )
    if config is not None:
        for artifact in config.artifacts:
            if artifact.path not in text:
                findings.append(
                    _error(
                        "prompt.md",
                        f"never names {artifact.path!r}, which grading.yaml grades; an "
                        f"artifact that is graded but not requested is not a fair test",
                    )
                )
    return findings


# ------------------------------------------------------------- data.manifest.json


def _check_manifest(task_dir: Path) -> list[Finding]:
    path = task_dir / "data.manifest.json"
    if not path.is_file():
        return []
    try:
        entries = json.loads(path.read_text())
    except json.JSONDecodeError as exc:
        return [_error("data.manifest.json", f"not valid JSON: {exc}")]
    if not isinstance(entries, list) or not entries:
        return [_error("data.manifest.json", "must be a non-empty list of entries")]

    findings = []
    seen: set[str] = set()
    for index, entry in enumerate(entries):
        where = f"data.manifest.json[{index}]"
        if not isinstance(entry, dict):
            findings.append(_error(where, "each entry must be a mapping"))
            continue

        target = entry.get("path")
        if not isinstance(target, str) or not target:
            findings.append(_error(where, "missing required field 'path'"))
        else:
            where = f"data.manifest.json[{target}]"
            if target in seen:
                findings.append(_error(where, "duplicate path"))
            seen.add(target)
            if target.startswith("/") or ".." in Path(target).parts:
                findings.append(_error(where, "path must be relative and stay inside the bundle"))
            elif Path(target).parts[0] not in {"data", "reference"}:
                findings.append(_error(where, "path must sit under data/ or reference/"))
            elif Path(target).parts[0] == "reference" and not entry.get("release"):
                findings.append(
                    _error(
                        where,
                        "a reference database must record its release; MIBiG, the "
                        "antiSMASH database and NP Atlas all move",
                    )
                )

        if not (entry.get("url") or entry.get("accession")):
            findings.append(_error(where, "needs a 'url' or an 'accession'"))

        checksum = entry.get("sha256")
        if not isinstance(checksum, str) or not SHA256.fullmatch(checksum):
            findings.append(
                _error(where, f"sha256 must be 64 lowercase hex characters, got {checksum!r}")
            )

        size = entry.get("bytes")
        if not isinstance(size, int) or isinstance(size, bool) or size <= 0:
            findings.append(_error(where, f"bytes must be a positive integer, got {size!r}"))
    return findings


# --------------------------------------------------------------------- grading.yaml


def _check_grading(config: GradingConfig) -> list[Finding]:
    findings = []
    truths = [a.truth for a in config.artifacts]
    for duplicate in sorted({t for t in truths if truths.count(t) > 1}):
        findings.append(_error("grading.yaml", f"two artifacts share truth file {duplicate!r}"))

    for artifact in config.artifacts:
        where = f"grading.yaml[{artifact.path}]"
        for label, value in (("path", artifact.path), ("truth", artifact.truth)):
            parts = Path(value).parts
            if value.startswith("/") or ".." in parts:
                findings.append(_error(where, f"{label} must be relative and stay inside the task"))
            elif label == "path" and parts and parts[0] == "outputs":
                findings.append(
                    _error(where, "path is relative to the agent's outputs/ directory, so it "
                                  "must not start with 'outputs/'")
                )

        declared = {m.type for m in artifact.metrics}
        if declared & ALIGNED_METRICS and "identifier_f1" not in declared:
            aligned = ", ".join(sorted(declared & ALIGNED_METRICS))
            findings.append(
                _error(
                    where,
                    f"declares {aligned} without identifier_f1. Aligned metrics only see "
                    f"the rows both files share, so on their own they do not notice a "
                    f"submission that dropped half the rows",
                )
            )
        if len(declared) != len(artifact.metrics):
            findings.append(_error(where, "declares the same metric type twice"))
    return findings


# ---------------------------------------------------------------------------- truth


def _check_truth(task_dir: Path, config: GradingConfig) -> list[Finding]:
    truth_dir = task_dir / "truth"
    if not truth_dir.is_dir():
        return [
            _note(
                "truth/",
                f"not present, so {len(config.artifacts)} truth checks were skipped; "
                f"run `make truth` then validate again",
            )
        ]
    findings = []
    for artifact in config.artifacts:
        findings.extend(_check_truth_file(truth_dir / artifact.truth, artifact))
    return findings


def _check_truth_file(path: Path, artifact) -> list[Finding]:
    from ..grading.artifact import SubmissionError, declared_columns, read_table, resolve_columns

    where = f"truth/{artifact.truth}"
    try:
        frame = read_table(path, artifact.separator)
        resolved, _ = resolve_columns(frame, declared_columns(artifact), artifact)
    except SubmissionError as exc:
        reason = str(exc)
        return [_error(where, UNREADABLE_TRUTH.get(reason, reason))]

    findings = []
    keys = [
        "\x1f".join(parts)
        for parts in zip(*(normalise_all(frame[resolved[c]], artifact.normalisers)
                           for c in artifact.row_key))
    ]
    duplicates = sorted({k for k in keys if keys.count(k) > 1})[:3]
    if duplicates:
        findings.append(
            _error(where, f"duplicate row keys after normalisation: "
                          f"{', '.join(k.replace(chr(31), '+') for k in duplicates)}")
        )

    for metric in artifact.metrics:
        if metric.type == "lins_ccc":
            findings.extend(_check_numeric_column(frame, resolved, metric, where))
        elif metric.type == "interval_overlap_f1":
            findings.extend(_check_interval_columns(frame, resolved, metric, where))
    return findings


def _check_numeric_column(frame, resolved, metric, where) -> list[Finding]:
    column = metric.params["column"]
    values = pd.to_numeric(frame[resolved[column]], errors="coerce")
    if values.isna().any():
        return [_error(where, f"column {column!r} is graded with CCC but holds "
                              f"non-numeric values")]
    if values.nunique() == 1:
        return [
            _error(
                where,
                f"column {column!r} is constant, so CCC is undefined on it; this "
                f"artifact needs a different metric",
            )
        ]
    if metric.params["log_transform"]:
        offset = metric.params["pseudocount"] or 0
        if (values + offset <= 0).any():
            return [
                _error(
                    where,
                    f"column {column!r} is log transformed but holds a non-positive "
                    f"value and no pseudocount rescues it",
                )
            ]
    return []


def _check_interval_columns(frame, resolved, metric, where) -> list[Finding]:
    starts = pd.to_numeric(frame[resolved[metric.params["start_column"]]], errors="coerce")
    ends = pd.to_numeric(frame[resolved[metric.params["end_column"]]], errors="coerce")
    if starts.isna().any() or ends.isna().any():
        return [_error(where, "interval coordinates must all be integers")]
    if (starts > ends).any():
        return [_error(where, "an interval has start > end; coordinates are 1-based inclusive")]
    return []


# ----------------------------------------------------------------------- entry point


def validate_task(task_dir: Path) -> list[Finding]:
    """Check one task bundle against the contract. An empty list means it passes."""
    findings = _check_layout(task_dir)
    findings.extend(_check_task_yaml(task_dir))
    findings.extend(_check_manifest(task_dir))
    findings.extend(_check_solution(task_dir))
    findings.extend(_check_environment(task_dir))

    config = None
    grading = task_dir / "grading.yaml"
    if grading.is_file():
        try:
            config = load_grading_config(grading)
        except ConfigError as exc:
            findings.append(_error("grading.yaml", str(exc)))

    findings.extend(_check_prompt(task_dir, config))
    if config is not None:
        findings.extend(_check_grading(config))
        findings.extend(_check_truth(task_dir, config))
    return findings


def report(findings: list[Finding]) -> str:
    errors = [f for f in findings if f.level == "error"]
    lines = [str(f) for f in findings]
    lines.append("")
    lines.append(f"{len(errors)} error(s), {len(findings) - len(errors)} note(s)")
    return "\n".join(lines)


# -------------------------------------------------------------------- solution steps


def solution_steps(task_dir: Path) -> list[str]:
    """The commands that regenerate truth/, as declared in task.yaml."""
    meta = yaml.safe_load((task_dir / "task.yaml").read_text())
    steps = ((meta or {}).get("solution") or {}).get("steps")
    if not (isinstance(steps, list) and steps and all(isinstance(s, str) for s in steps)):
        raise ValueError(
            f"{task_dir / 'task.yaml'}: solution.steps must be a non-empty list of "
            f"command strings, so truth/ can be regenerated from a committed script"
        )
    return steps
