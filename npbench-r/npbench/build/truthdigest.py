"""A committed fingerprint of truth/, which is itself not committed.

`tasks/*/truth/` is gitignored on purpose: it is generated by a committed
script from checksummed inputs, and CLAUDE.md says raw and derived payloads
stay out of git. The gap that leaves is that the answer key becomes
unverifiable. A dependency bump, an edit to a solution script, or a silently
different reference release would all produce a different truth/, and nothing
would say so -- while every score the benchmark has ever reported was computed
against the old one.

So the payload stays out and the fingerprint goes in: one sha256 and one row
count per artifact. It is small, it is diffable, and `npbench validate` checks
it whenever both the digest and truth/ are present. Regenerating truth and
finding the digest unchanged is the evidence that a published score still
means what it meant.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass
from pathlib import Path

DIGEST_FILE = "truth.digest.json"


@dataclass(frozen=True)
class DigestEntry:
    path: str
    sha256: str
    rows: int


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def _rows(path: Path) -> int:
    """Data rows, so the header is not counted."""
    with path.open("rb") as handle:
        return max(sum(1 for _ in handle) - 1, 0)


def measure(task_dir: Path) -> list[DigestEntry]:
    truth = task_dir / "truth"
    if not truth.is_dir():
        return []
    return [
        DigestEntry(path=f.name, sha256=_sha256(f), rows=_rows(f))
        for f in sorted(truth.iterdir())
        if f.is_file()
    ]


def write(task_dir: Path) -> list[DigestEntry]:
    entries = measure(task_dir)
    payload = [{"path": e.path, "sha256": e.sha256, "rows": e.rows} for e in entries]
    (task_dir / DIGEST_FILE).write_text(json.dumps(payload, indent=2) + "\n")
    return entries


def load(task_dir: Path) -> list[DigestEntry] | None:
    path = task_dir / DIGEST_FILE
    if not path.is_file():
        return None
    raw = json.loads(path.read_text())
    return [DigestEntry(r["path"], r["sha256"], int(r["rows"])) for r in raw]


def compare(task_dir: Path) -> list[str]:
    """Differences between the committed digest and the truth/ on disk.

    Returns an empty list when they agree, and when there is nothing to compare
    against: a task with no digest yet, or a fresh checkout where `truth/` has
    never been generated. The test is whether the *directory* exists, not
    whether it holds anything -- an existing but incomplete `truth/` is exactly
    the case worth reporting, and treating it as unfetched would hide a deleted
    artifact.
    """
    recorded = load(task_dir)
    if recorded is None or not (task_dir / "truth").is_dir():
        return []
    current = measure(task_dir)

    by_name = {e.path: e for e in current}
    problems = []
    for entry in recorded:
        found = by_name.pop(entry.path, None)
        if found is None:
            problems.append(f"{entry.path}: in the digest but missing from truth/")
            continue
        if found.sha256 != entry.sha256:
            problems.append(
                f"{entry.path}: truth/ has changed since the digest was written "
                f"({entry.rows} rows then, {found.rows} now). Either the digest is "
                f"stale and should be rewritten with `npbench digest`, or something "
                f"changed that invalidates every score computed against it."
            )
    for name in sorted(by_name):
        problems.append(f"{name}: in truth/ but not in the digest")
    return problems
